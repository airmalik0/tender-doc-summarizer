"""Схемы, которые заполняет LLM.

Отделены от схем ответа API намеренно. Модель заполняет «сырой» слой:
только то, что она увидела в тексте, вместе с цитатой-подтверждением.
Разбор дат, приведение сумм к Decimal, проверка цитат по исходному тексту
и расчёт достоверности — это уже наш код (app/services/extraction), и он
не должен зависеть от того, что модель напишет в поле.

Два неочевидных решения в этом файле.

Первое: здесь нет ограничений вроде minLength или ge. Схема уходит
провайдеру в режиме строгого структурированного вывода, а он поддерживает
лишь подмножество JSON Schema. Валидация значений живёт в слое разбора.

Второе: здесь нет и Optional. Anthropic ограничивает число параметров с
union-типами (лимит 16 на схему), а схема с nullable-полями на каждое
значение упиралась в него на 35 параметрах и получала 400. Поэтому
отсутствие данных выражается пустым значением: пустая строка, ноль, нулевая
страница. Ровно для этого у моделей есть свойство is_empty — приводить
пустышки к None положено при слиянии, а не заставлять модель выбирать
между null и объектом.
"""

from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field

VatMode = Literal["включён", "не включён", "не указано"]
LawKind = Literal["44-ФЗ", "223-ФЗ", "не определено"]
RequirementCategory = Literal[
    "опыт",
    "лицензии и допуски",
    "квалификация персонала",
    "материально-техническая база",
    "финансовые гарантии",
    "требования к товару или работам",
    "прочее",
]
PenaltyKind = Literal["пеня", "штраф", "иная мера ответственности"]
PenaltyParty = Literal["исполнитель", "заказчик", "обе стороны", "не указано"]

# Цитата короче этого считается бессодержательной и не проверяется.
MIN_MEANINGFUL_QUOTE = 8


class RawEvidence(BaseModel):
    """Ссылка на место в документе, подтверждающее извлечённое значение."""

    page: int = Field(
        description=(
            "Номер страницы из маркера [СТРАНИЦА N], на которой находится подтверждение. "
            "0 — если подтверждения нет."
        )
    )
    quote: str = Field(
        description=(
            "Дословная цитата из документа, подтверждающая значение: от 10 до 300 символов. "
            "Копировать посимвольно из текста, ничего не перефразировать и не сокращать. "
            "Цитата автоматически проверяется поиском по исходному тексту, поэтому "
            "выдуманная или пересказанная цитата будет помечена как неподтверждённая. "
            "Пустая строка — если подтверждения нет."
        )
    )

    @property
    def is_empty(self) -> bool:
        return self.page <= 0 or len(self.quote.strip()) < MIN_MEANINGFUL_QUOTE


class RawMoney(BaseModel):
    """Денежная величина в том виде, в каком её нашла модель."""

    amount: float = Field(
        description=(
            "Число в рублях без разделителей разрядов, копейки — после точки, "
            "например 12480350.00. Ноль — если суммы во фрагменте нет."
        )
    )
    currency: str = Field(description="Код валюты, обычно RUB. Пустая строка — если не указана.")
    vat: VatMode = Field(description="Включён ли НДС в сумму по тексту документа.")
    raw_text: str = Field(
        description=(
            "Сумма так, как она написана в документе, включая прописную расшифровку. "
            "Пустая строка — если суммы нет."
        )
    )
    evidence: RawEvidence = Field(description="Цитата, подтверждающая сумму.")

    @property
    def is_empty(self) -> bool:
        return self.amount <= 0 and not self.raw_text.strip()


class RawDate(BaseModel):
    """Срок в том виде, в каком его нашла модель."""

    iso_date: str = Field(
        description=(
            "Дата в формате ГГГГ-ММ-ДД. Пустая строка, если в документе указан только "
            "относительный срок («в течение 45 дней с даты заключения контракта») — "
            "тогда сам срок вынести в raw_text."
        )
    )
    raw_text: str = Field(
        description=(
            "Формулировка срока так, как она написана в документе. "
            "Пустая строка — если срока нет."
        )
    )
    evidence: RawEvidence = Field(description="Цитата, подтверждающая срок.")

    @property
    def is_empty(self) -> bool:
        return not self.iso_date.strip() and not self.raw_text.strip()


class RawStage(BaseModel):
    """Этап выполнения работ или поставки."""

    name: str = Field(description="Краткое название этапа, до 120 символов.")
    deadline_text: str = Field(
        description="Срок этапа так, как он сформулирован в документе. Пустая строка, если срок не указан."
    )
    evidence: RawEvidence = Field(description="Цитата, подтверждающая этап и его срок.")


class RawRequirement(BaseModel):
    """Требование к участнику закупки или к предмету закупки."""

    text: str = Field(
        description=(
            "Требование одной ёмкой фразой на русском языке, до 250 символов. "
            "Сохранять числовые пороги: проценты, суммы, количество специалистов, "
            "сроки гарантии."
        )
    )
    category: RequirementCategory = Field(description="Категория требования.")
    mandatory: bool = Field(
        description=(
            "true — требование обязательно для допуска к закупке; "
            "false — требование желательное либо применяется только в отдельных случаях."
        )
    )
    evidence: RawEvidence = Field(description="Цитата, подтверждающая требование.")


class RawPenalty(BaseModel):
    """Мера ответственности: пеня, штраф или иная санкция."""

    kind: PenaltyKind = Field(
        description=(
            "пеня — санкция, начисляемая за каждый день просрочки; "
            "штраф — разовая санкция за факт нарушения; "
            "иная мера ответственности — односторонний отказ, удержание обеспечения и подобное."
        )
    )
    party: PenaltyParty = Field(description="Сторона, на которую налагается санкция.")
    trigger: str = Field(description="За что применяется санкция, кратко и по существу.")
    calculation: str = Field(
        description=(
            "Порядок расчёта дословно по документу, например «1/300 ключевой ставки ЦБ РФ "
            "от цены контракта за каждый день просрочки». Пустая строка, если расчёт не описан."
        )
    )
    amount_text: str = Field(
        description=(
            "Размер санкции, если он указан явно, например «374 410,50 рубля» или «3%». "
            "Пустая строка, если размер не указан."
        )
    )
    evidence: RawEvidence = Field(description="Цитата, подтверждающая санкцию.")


class ChunkExtraction(BaseModel):
    """Результат извлечения из одного фрагмента документа.

    Пустые значения — норма: фрагмент может не содержать ни цены, ни сроков,
    и выдумывать их, лишь бы заполнить схему, модель не должна.
    """

    subject: str = Field(description="Предмет закупки одной строкой. Пустая строка, если во фрагменте его нет.")
    customer: str = Field(description="Полное наименование заказчика. Пустая строка, если его нет.")
    procurement_number: str = Field(
        description="Номер извещения или закупки, обычно 19 цифр. Пустая строка, если его нет."
    )
    law: LawKind = Field(description="Закон, по которому проводится закупка.")

    price: RawMoney = Field(
        description=(
            "Начальная (максимальная) цена контракта — НМЦК, либо цена контракта. "
            "Не обеспечение заявки и не обеспечение исполнения контракта."
        )
    )
    contract_security: RawMoney = Field(
        description="Размер обеспечения исполнения контракта. Не обеспечение заявки."
    )

    application_deadline: RawDate = Field(description="Дата и время окончания подачи заявок.")
    contract_start: RawDate = Field(description="Дата начала исполнения контракта.")
    contract_end: RawDate = Field(
        description="Крайняя дата исполнения контракта или окончания работ."
    )
    duration_text: str = Field(
        description=(
            "Срок исполнения целиком, как он сформулирован в документе, например "
            "«с даты заключения контракта по 20 декабря 2026 года». Пустая строка, если срока нет."
        )
    )

    stages: list[RawStage] = Field(
        description="Этапы работ или поставки. Пустой список, если их нет."
    )
    requirements: list[RawRequirement] = Field(
        description=(
            "Ключевые требования к исполнителю. Только содержательные: не переписывать "
            "весь текст закона, а зафиксировать то, что реально ограничивает круг участников."
        )
    )
    penalties: list[RawPenalty] = Field(
        description="Все меры ответственности, найденные во фрагменте."
    )


class DocumentSynthesis(BaseModel):
    """Итоговая выжимка, которая собирается по уже извлечённым фактам."""

    summary: str = Field(
        description=(
            "Связная выжимка на русском языке, 4–7 предложений: что закупается, кем, "
            "за какую сумму, в какие сроки и на каких ключевых условиях. Без воды "
            "и без повторения списков — только суть, важная для решения об участии."
        )
    )
    risks: list[str] = Field(
        description=(
            "От двух до пяти конкретных рисков для потенциального исполнителя: жёсткие "
            "сроки, крупные штрафы, барьеры входа, отсутствие аванса. Каждый риск — "
            "одно предложение. Если рисков не видно, вернуть пустой список."
        )
    )
